"""Clean the raw Blinkit CSV and export it for the interactive dashboard.

Applies the same cleaning rules as blinkit-grocery-analysis.sql so the
SQL results and the dashboard agree. Writes:
  data/blinkit_clean.csv          cleaned row-level data
  interactive-dashboard/data.js   compact copy loaded by index.html

Run from the project root:  python scripts/build_dashboard_data.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "Contain_Raw_Data.csv"
CLEAN = ROOT / "data" / "blinkit_clean.csv"
DASH_DATA = ROOT / "interactive-dashboard" / "data.js"

FAT_MAP = {"LF": "Low Fat", "low fat": "Low Fat", "Low Fat": "Low Fat",
           "reg": "Regular", "Regular": "Regular"}


def price_tier(mrp: float) -> str:
    if mrp < 50:
        return "Budget (<50)"
    if mrp < 100:
        return "Mid (50-99)"
    if mrp < 200:
        return "Premium (100-199)"
    return "Luxury (200+)"


def clean(df: pd.DataFrame) -> pd.DataFrame:
    df = df.copy()

    # 1. Fat content: merge the five spellings into two labels, then mark
    #    non-consumables (NC* items: household, hygiene, others) as Non-Edible.
    df["Item_Fat_Content"] = df["Item_Fat_Content"].map(FAT_MAP)
    df.loc[df["Item_Identifier"].str.startswith("NC"), "Item_Fat_Content"] = "Non-Edible"

    # 2. Outlet size is missing for three whole outlets; keep them, but label them.
    df["Outlet_Size"] = df["Outlet_Size"].fillna("Unknown")

    # 3. Item weight is a product attribute, identical across outlets, so fill
    #    gaps from the same Item_Identifier elsewhere in the data.
    df["Item_Weight"] = df.groupby("Item_Identifier")["Item_Weight"].transform(
        lambda s: s.fillna(s.mean()))

    # 4. A visibility of 0 is impossible for an item that sold; replace it
    #    with that item's average non-zero visibility.
    nonzero = df["Item_Visibility"].where(df["Item_Visibility"] > 0)
    df["Item_Visibility"] = nonzero.fillna(
        nonzero.groupby(df["Item_Identifier"]).transform("mean"))

    df["Price_Tier"] = df["Item_MRP"].apply(price_tier)
    return df


def export_dashboard(df: pd.DataFrame) -> None:
    """Dictionary-encode categoricals so the payload stays small."""
    cats = {c: sorted(df[c].unique()) for c in ("Item_Type", "Item_Fat_Content")}
    outlets = (df.groupby("Outlet_Identifier")
                 [["Outlet_Size", "Outlet_Location_Type", "Outlet_Type",
                   "Outlet_Establishment_Year"]].first())
    outlet_ids = list(outlets.index)

    rows = [
        [r.Item_Identifier,
         cats["Item_Type"].index(r.Item_Type),
         cats["Item_Fat_Content"].index(r.Item_Fat_Content),
         outlet_ids.index(r.Outlet_Identifier),
         round(r.Item_MRP, 2),
         round(r.Item_Outlet_Sales, 2),
         round(r.Item_Visibility, 4)]
        for r in df.itertuples()
    ]
    payload = {
        "itemTypes": cats["Item_Type"],
        "fatContents": cats["Item_Fat_Content"],
        "outlets": [
            {"id": oid, "size": o.Outlet_Size, "tier": o.Outlet_Location_Type,
             "type": o.Outlet_Type, "year": int(o.Outlet_Establishment_Year)}
            for oid, o in outlets.iterrows()
        ],
        "columns": ["item", "type", "fat", "outlet", "mrp", "sales", "visibility"],
        "rows": rows,
    }
    DASH_DATA.parent.mkdir(exist_ok=True)
    DASH_DATA.write_text(
        "// Generated by scripts/build_dashboard_data.py - do not edit by hand.\n"
        "window.BLINKIT_DATA = " + json.dumps(payload, separators=(",", ":")) + ";\n",
        encoding="utf-8")


def main() -> None:
    df = clean(pd.read_csv(RAW))
    CLEAN.parent.mkdir(exist_ok=True)
    df.to_csv(CLEAN, index=False)
    export_dashboard(df)

    print(f"Rows: {len(df):,}  |  products: {df['Item_Identifier'].nunique():,}  |  "
          f"outlets: {df['Outlet_Identifier'].nunique()}")
    print(f"Total sales: {df['Item_Outlet_Sales'].sum():,.2f}  |  "
          f"average per row: {df['Item_Outlet_Sales'].mean():,.2f}")
    print(f"Weights still missing: {df['Item_Weight'].isna().sum()}")
    print(f"Wrote {CLEAN.relative_to(ROOT)} and {DASH_DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
